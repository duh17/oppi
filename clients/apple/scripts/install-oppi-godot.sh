#!/usr/bin/env bash
# Installs the Godot pane's engine (OppiGodot.xcframework) into Vendor/ when
# this machine has built it, and removes it when it has not.
#
# Unlike the other Vendor/ frameworks, the engine is optional and never built
# here: a Godot build takes minutes and needs the Godot sources, so it is an
# explicit `engine/godot/build.sh`, which puts the product in a local cache
# keyed by its inputs (BUILD_ID). This script copies the product for the
# current BUILD_ID from that cache and writes Vendor/OppiGodot/OppiGodot.xcconfig,
# which Base.xcconfig includes: the include path makes `canImport(OppiGodot)`
# true and the Oppi target links the library. With no product for the
# current id (CI, a fresh machine, OPPI_GODOT=off) Vendor/OppiGodot/ is
# removed, nothing links, and the app reports that it has no game engine.
# OPPI_GODOT_VARIANT picks another variant build.sh made (stripped-size, to
# measure its frame time on a device); the product is stripped.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENGINE="$ROOT/../../engine/godot"
VENDOR="$ROOT/Vendor/OppiGodot"
CACHE="${OPPI_GODOT_CACHE:-$HOME/Library/Caches/oppi-godot}"

remove() {
    if [[ -d "$VENDOR" ]]; then
        rm -rf "$VENDOR"
        echo "Removed the Godot pane engine from Vendor/ ($1)."
    else
        echo "Godot pane engine not installed ($1)."
    fi
}

if [[ "${OPPI_GODOT:-}" == off ]]; then
    remove "OPPI_GODOT=off"
    exit 0
fi
BUILD_ID="$(VARIANT="${OPPI_GODOT_VARIANT:-stripped}" "$ENGINE/build.sh" --print-id)"
if [[ -f "$VENDOR/BUILD_ID" && "$(<"$VENDOR/BUILD_ID")" == "$BUILD_ID" && -f "$VENDOR/OppiGodot.xcconfig" ]]; then
    echo "OppiGodot is current ($BUILD_ID)."
    exit 0
fi
product="$CACHE/$BUILD_ID"
if [[ ! -f "$product/BUILD_ID" || ! -d "$product/OppiGodot.xcframework/ios-arm64" ||
      ! -d "$product/OppiGodot.xcframework/ios-arm64-simulator" ]]; then
    remove "no build of $BUILD_ID; run engine/godot/build.sh to add it"
    exit 0
fi

device="$(cd "$product/OppiGodot.xcframework/ios-arm64" && ls libgodot.*.a)"
simulator="$(cd "$product/OppiGodot.xcframework/ios-arm64-simulator" && ls libgodot.*.a)"
tmp="$VENDOR.tmp.$$"
rm -rf "$tmp"
mkdir -p "$tmp"
# A clone on APFS when the cache shares the volume; a copy otherwise.
cp -Rc "$product/OppiGodot.xcframework" "$tmp/" 2>/dev/null || cp -R "$product/OppiGodot.xcframework" "$tmp/"
cat > "$tmp/OppiGodot.xcconfig" <<EOF
// Generated by scripts/install-oppi-godot.sh for $BUILD_ID; do not edit.
// The Godot pane's engine: Swift finds the OppiGodot module on iOS devices and
// the simulator, and the Oppi target links it (OPPI_GODOT_LDFLAGS).
OPPI_GODOT_XCFRAMEWORK = \$(PROJECT_DIR)/Vendor/OppiGodot/OppiGodot.xcframework
SWIFT_INCLUDE_PATHS[sdk=iphoneos*] = \$(inherited) \$(OPPI_GODOT_XCFRAMEWORK)/ios-arm64/Headers
SWIFT_INCLUDE_PATHS[sdk=iphonesimulator*] = \$(inherited) \$(OPPI_GODOT_XCFRAMEWORK)/ios-arm64-simulator/Headers
OPPI_GODOT_LDFLAGS[sdk=iphoneos*] = \$(OPPI_GODOT_XCFRAMEWORK)/ios-arm64/$device
OPPI_GODOT_LDFLAGS[sdk=iphonesimulator*] = \$(OPPI_GODOT_XCFRAMEWORK)/ios-arm64-simulator/$simulator
EOF
printf '%s\n' "$BUILD_ID" > "$tmp/BUILD_ID"
rm -rf "$VENDOR"
mv "$tmp" "$VENDOR"
echo "Installed the Godot pane engine ($BUILD_ID)."
