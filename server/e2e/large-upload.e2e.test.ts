/**
 * E2E: large attachment uploads through the real upload routes.
 *
 * 1. An 800 MiB body sent over a throttled link that takes well over 30 seconds
 *    completes, with the server's size and sha256 matching what was sent.
 * 2. A connection dropped mid-body leaves the upload waiting: sending it again to the
 *    same URL (what iOS does for a background upload) completes, as does a new upload
 *    of the same file (what the app's own retry does).
 *
 * The body is generated as it is sent, never held whole in memory.
 */

import { createHash } from "node:crypto";
import { request as httpRequest } from "node:http";
import { request as httpsRequest } from "node:https";

import { beforeAll, describe, expect, inject, it } from "vitest";

import {
  api,
  baseURL,
  createWorkspace,
  createWorkspaceSession,
  currentE2EAccessToken,
  e2eWorkspaceHostMount,
  isSecureTransport,
  pairFreshDevice,
} from "./harness.js";

const MIB = 1024 * 1024;

interface PutResult {
  status: number;
  body: string;
  elapsedMs: number;
  sha256: string;
}

/**
 * PUTs `totalBytes` generated bytes at about `bytesPerSecond`. `dropAfterBytes`
 * destroys the connection once that much was sent, as a phone losing its network does.
 */
function throttledPut(
  path: string,
  bearer: string,
  totalBytes: number,
  bytesPerSecond: number,
  dropAfterBytes?: number,
): Promise<PutResult> {
  const url = new URL(path, baseURL());
  const send = isSecureTransport() ? httpsRequest : httpRequest;
  const hash = createHash("sha256");
  const started = Date.now();
  return new Promise((resolve, reject) => {
    const req = send(url, {
      method: "PUT",
      headers: {
        Authorization: `Bearer ${bearer}`,
        "Content-Type": "video/mp4",
        "Content-Length": String(totalBytes),
      },
      ...(isSecureTransport() ? { rejectUnauthorized: false } : {}),
    });
    req.on("response", (res) => {
      let body = "";
      res.setEncoding("utf8");
      res.on("data", (chunk: string) => (body += chunk));
      res.on("end", () =>
        resolve({
          status: res.statusCode ?? 0,
          body,
          elapsedMs: Date.now() - started,
          sha256: hash.digest("hex"),
        }),
      );
    });
    req.on("error", reject);

    const chunkBytes = MIB;
    let sent = 0;
    let index = 0;
    const pump = (): void => {
      while (sent < totalBytes) {
        if (dropAfterBytes !== undefined && sent >= dropAfterBytes) {
          req.destroy(new Error("dropped by test"));
          return;
        }
        // Stay on schedule: never ahead of `bytesPerSecond`.
        const due = started + (sent / bytesPerSecond) * 1000;
        if (Date.now() < due) {
          setTimeout(pump, due - Date.now());
          return;
        }
        const size = Math.min(chunkBytes, totalBytes - sent);
        const chunk = Buffer.alloc(size, index % 251);
        chunk.writeUInt32BE(index, 0);
        index += 1;
        sent += size;
        hash.update(chunk);
        if (!req.write(chunk)) {
          req.once("drain", pump);
          return;
        }
      }
      req.end();
    };
    pump();
  });
}

describe("E2E: large attachment uploads", { timeout: 600_000 }, () => {
  const lmsReady = () => inject("e2eLmsReady");
  let token = "";
  let workspaceId = "";
  let sessionId = "";

  const attachmentsPath = () =>
    `/workspaces/${encodeURIComponent(workspaceId)}/sessions/${encodeURIComponent(sessionId)}/attachments`;

  async function createUpload(sizeBytes: number): Promise<string> {
    const created = await api("POST", attachmentsPath(), token, {
      name: "screen-recording.mp4",
      mimeType: "video/mp4",
      sizeBytes,
      purpose: "chat_attachment",
    });
    expect(created.status, created.text).toBe(201);
    return created.json?.uploadId as string;
  }

  beforeAll(async () => {
    if (!lmsReady()) return;
    token = await pairFreshDevice("e2e-large-upload");
    const workspace = await createWorkspace(token, {
      name: `large-upload-${Date.now()}`,
      hostMount: e2eWorkspaceHostMount(),
    });
    workspaceId = workspace.id as string;
    const session = await createWorkspaceSession(token, workspaceId, { model: inject("e2eModel") });
    sessionId = session.id as string;
  });

  it("completes an 800 MiB upload over a link that takes more than 30 seconds", async () => {
    if (!lmsReady()) return;
    const sizeBytes = 800 * MIB;
    const uploadId = await createUpload(sizeBytes);

    // ~22 MiB/s: about 36 seconds for the whole body.
    const result = await throttledPut(
      `${attachmentsPath()}/${uploadId}/content`,
      await currentE2EAccessToken(token),
      sizeBytes,
      22 * MIB,
    );

    expect(result.status, result.body).toBe(200);
    expect(result.elapsedMs).toBeGreaterThan(30_000);
    const { attachment } = JSON.parse(result.body) as {
      attachment: { id: string; sizeBytes: number; sha256: string; mimeType: string };
    };
    expect(attachment).toMatchObject({
      id: uploadId,
      sizeBytes,
      sha256: result.sha256,
      mimeType: "video/mp4",
    });
    console.log(
      `[e2e] 800 MiB upload: ${(result.elapsedMs / 1000).toFixed(1)} s, ` +
        `${((sizeBytes / MIB / result.elapsedMs) * 1000).toFixed(1)} MiB/s`,
    );
  });

  it("completes an upload resent after its connection was cut mid-body", async () => {
    if (!lmsReady()) return;
    const sizeBytes = 200 * MIB;
    const firstId = await createUpload(sizeBytes);

    await expect(
      throttledPut(
        `${attachmentsPath()}/${firstId}/content`,
        await currentE2EAccessToken(token),
        sizeBytes,
        100 * MIB,
        64 * MIB,
      ),
    ).rejects.toThrow("dropped by test");

    // iOS resends a dropped background upload to the same URL; the server starts it over.
    const resent = await throttledPut(
      `${attachmentsPath()}/${firstId}/content`,
      await currentE2EAccessToken(token),
      sizeBytes,
      200 * MIB,
    );
    expect(resent.status, resent.body).toBe(200);
    expect(JSON.parse(resent.body).attachment).toMatchObject({
      id: firstId,
      sizeBytes,
      sha256: resent.sha256,
    });

    // The app's own retry, after the system gives up, is a new upload of the whole file.
    const retryId = await createUpload(sizeBytes);
    const retried = await throttledPut(
      `${attachmentsPath()}/${retryId}/content`,
      await currentE2EAccessToken(token),
      sizeBytes,
      200 * MIB,
    );
    expect(retried.status, retried.body).toBe(200);
    expect(JSON.parse(retried.body).attachment).toMatchObject({ id: retryId, sizeBytes });
  });
});
