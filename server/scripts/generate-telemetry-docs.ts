#!/usr/bin/env bun

/**
 * Generate the event tables of dev/telemetry.md from the telemetry catalog.
 *
 *   bun server/scripts/generate-telemetry-docs.ts          # rewrite the tables
 *   bun server/scripts/generate-telemetry-docs.ts --check  # exit 1 when stale
 *
 * Only the text between the BEGIN and END markers is generated; everything else
 * in the page is hand-written. `check-telemetry.ts` fails `npm run check` while
 * the tables are stale.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  EVENT_DEFS,
  GROUPS,
  TAG_DEFS,
  fieldSpec,
  type EventDef,
  type GroupKey,
  type TagDef,
} from "../src/telemetry/catalog.ts";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const DOCS_PATH = join(repoRoot, "dev/telemetry.md");

export const BEGIN_MARKER =
  "<!-- telemetry-catalog:begin (generated by server/scripts/generate-telemetry-docs.ts; do not edit) -->";
export const END_MARKER = "<!-- telemetry-catalog:end -->";

const cell = (text: string): string => text.replaceAll("|", "\\|").replaceAll("\n", " ");

function fieldsCell(event: EventDef): string {
  const fields = Object.entries(event.fields).map(([key, def]) => {
    const spec = fieldSpec(def);
    return `\`${key}\` ${spec.unit}${spec.optional ? " (optional)" : ""}`;
  });
  return fields.length > 0 ? fields.join("<br>") : "none";
}

function tagsCell(event: EventDef, tags: Readonly<Record<string, TagDef>>): string {
  const uses = Object.entries(event.tags ?? {}).map(([key, use]) => {
    const def = tags[key];
    const kind = def?.kind === "bucket" ? " (bucket)" : "";
    const values = use.values ? `: ${use.values.map((value) => `\`${value}\``).join(", ")}` : "";
    return `\`${key}\`${use.required ? "*" : ""}${kind}${values}`;
  });
  return uses.length > 0 ? uses.join("<br>") : "none";
}

function where(filter: Readonly<Record<string, readonly string[]>> | undefined): string {
  if (!filter) return "";
  return ` when ${Object.entries(filter)
    .map(([key, values]) => `${key}=${values.join("|")}`)
    .join(", ")}`;
}

function policyCell(event: EventDef): string {
  const lines: string[] = [];
  for (const rule of event.emit ?? []) {
    const bounds = [
      rule.min !== undefined ? `≥ ${rule.min}` : "",
      rule.max !== undefined ? `< ${rule.max}` : "",
    ]
      .filter(Boolean)
      .join(", ");
    lines.push(`emit \`${rule.field}\` ${bounds}${where(rule.where)}`);
  }
  if (event.storage) {
    const ops = Object.entries(event.storage.aggregate)
      .map(([field, op]) => `${op} \`${field}\``)
      .join(", ");
    lines.push(`aggregate per 60 s: ${ops}`);
  }
  for (const slo of event.slo ?? []) {
    const direction = slo.lowerIsBad ? "≥" : "≤";
    lines.push(`SLO \`${slo.field}\` TM99 ${direction} ${slo.tm99}${where(slo.where)}`);
  }
  return lines.length > 0 ? lines.join("<br>") : "none";
}

/** Markdown for every event, one table per group, in catalog order. */
export function renderEventTables(
  events: Readonly<Record<string, EventDef>> = EVENT_DEFS,
  tags: Readonly<Record<string, TagDef>> = TAG_DEFS,
): string {
  const sections: string[] = [
    'Generated from `server/src/telemetry/catalog.ts`. A `*` marks a required tag; a field without "(optional)" is always present.',
  ];
  for (const [group, meta] of Object.entries(GROUPS)) {
    const rows = Object.entries(events).filter(([, event]) => event.group === (group as GroupKey));
    if (rows.length === 0) continue;
    sections.push(
      `#### ${meta.label}`,
      meta.note,
      [
        "| Event | Answers | Fields | Tags | Emit, storage, SLO |",
        "| --- | --- | --- | --- | --- |",
        ...rows.map(
          ([name, event]) =>
            `| \`${name}\` | ${cell(event.description)} | ${cell(fieldsCell(event))} | ${cell(tagsCell(event, tags))} | ${cell(policyCell(event))} |`,
        ),
      ].join("\n"),
    );
  }
  return sections.join("\n\n");
}

/** `page` with the generated block replaced; null when the markers are missing or misordered. */
export function withGeneratedTables(page: string, generated = renderEventTables()): string | null {
  const begin = page.indexOf(BEGIN_MARKER);
  const end = page.indexOf(END_MARKER);
  if (begin === -1 || end === -1 || end < begin) return null;
  return `${page.slice(0, begin + BEGIN_MARKER.length)}\n\n${generated}\n\n${page.slice(end)}`;
}

function main(): void {
  const page = readFileSync(DOCS_PATH, "utf8");
  const next = withGeneratedTables(page);
  if (next === null) {
    console.error(`${DOCS_PATH}: missing ${BEGIN_MARKER} / ${END_MARKER}`);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    if (next !== page) {
      console.error(
        "dev/telemetry.md event tables are stale. Run: bun server/scripts/generate-telemetry-docs.ts",
      );
      process.exit(1);
    }
    return;
  }
  if (next !== page) writeFileSync(DOCS_PATH, next);
}

if (import.meta.main) {
  main();
}
