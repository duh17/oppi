import { afterEach, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { checkDocs, longParagraphs } from "./dev-docs-guard";

const temps: string[] = [];
afterEach(() => {
  for (const dir of temps.splice(0)) rmSync(dir, { recursive: true, force: true });
});

/** A checkout holding `files` (repo-relative path → text) and the budget file built from `words`. */
function checkout(files: Record<string, string>, words: Record<string, number>, maxParagraphChars = 1200): string {
  const root = mkdtempSync(join(tmpdir(), "dev-docs-guard-"));
  temps.push(root);
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  mkdirSync(join(root, "dev"), { recursive: true });
  writeFileSync(join(root, "dev/doc-budgets.json"), JSON.stringify({ reason: "test", maxParagraphChars, words }));
  return root;
}

const sentence = (chars: number) => `${"x".repeat(chars - 1)}.`;

describe("word budgets", () => {
  test("a doc over its budget fails with its count, its budget, and the standard", () => {
    const root = checkout({ "dev/a.md": "one two three four five\n" }, { "dev/a.md": 4 });
    const failures = checkDocs(root);
    expect(failures).toHaveLength(1);
    expect(failures[0]).toContain("dev/a.md");
    expect(failures[0]).toContain("5 words");
    expect(failures[0]).toContain("budget 4");
    expect(failures[0]).toContain("dev/README.md");
  });

  test("a doc at its budget passes", () => {
    const root = checkout({ "dev/a.md": "one two three four\n" }, { "dev/a.md": 4 });
    expect(checkDocs(root)).toEqual([]);
  });

  test("a generated region between begin/end markers does not count, so a catalog change cannot break a budget", () => {
    const generated = "<!-- catalog:begin (generated by gen.ts; do not edit) -->\n\n| a | b | c | d | e | f |\n\n<!-- catalog:end -->\n";
    const root = checkout({ "dev/a.md": `one two\n\n${generated}\nthree\n` }, { "dev/a.md": 3 });
    expect(checkDocs(root)).toEqual([]);
  });

  test("a dev doc with no budget entry fails, in nested folders too", () => {
    const root = checkout({ "dev/a.md": "a\n", "dev/testing/b.md": "b\n" }, { "dev/a.md": 10 });
    const failures = checkDocs(root);
    expect(failures).toHaveLength(1);
    expect(failures[0]).toContain("dev/testing/b.md");
    expect(failures[0]).toContain("no budget");
  });

  test("a budget entry whose doc is gone fails, so the file cannot rot", () => {
    const root = checkout({ "dev/a.md": "a\n" }, { "dev/a.md": 10, "dev/gone.md": 10 });
    const failures = checkDocs(root);
    expect(failures).toHaveLength(1);
    expect(failures[0]).toContain("dev/gone.md");
  });
});

describe("paragraph length", () => {
  test("a wrapped paragraph is measured across its lines", () => {
    const text = `# Title\n\n${sentence(700)}\n${sentence(700)}\n`;
    expect(longParagraphs(text, 1200)).toEqual([{ line: 3, chars: 1401 }]);
  });

  test("each list item is its own paragraph, and a continuation line belongs to its item", () => {
    const short = `- ${sentence(700)}\n- ${sentence(700)}\n`;
    expect(longParagraphs(short, 1200)).toEqual([]);
    const long = `- ${sentence(100)}\n- ${sentence(700)}\n  ${sentence(700)}\n`;
    expect(longParagraphs(long, 1200)).toEqual([{ line: 2, chars: 1403 }]);
  });

  test("tables and fenced code are not paragraphs", () => {
    const row = `| ${"x".repeat(1500)} |`;
    const text = `${row}\n${row}\n\n\`\`\`\n${"y".repeat(1500)}\n\`\`\`\n`;
    expect(longParagraphs(text, 1200)).toEqual([]);
  });

  test("a long paragraph fails the check with its line and the limit", () => {
    const root = checkout({ "dev/a.md": `intro\n\n${sentence(1300)}\n` }, { "dev/a.md": 100 });
    const failures = checkDocs(root);
    expect(failures).toHaveLength(1);
    expect(failures[0]).toContain("dev/a.md:3");
    expect(failures[0]).toContain("1300 characters");
    expect(failures[0]).toContain("1200");
  });
});
